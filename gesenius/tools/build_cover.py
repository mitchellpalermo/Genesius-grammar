"""The print edition's wrap-around cover (back, spine, front) as one PDF.

    python3 tools/build_cover.py                      # spine from build/book-print.pdf, white paper
    python3 tools/build_cover.py --paper cream
    python3 tools/build_cover.py --guides             # also draw trim, spine and safe-area lines
    (cd build && typst compile --font-path ../fonts cover.typ cover.pdf)

The spine width depends on the page count and the paper, so rebuild the cover
whenever the interior's page count changes. Paper thickness below is KDP's
(inches per page); IngramSpark's differs slightly: take its value from the
cover template it generates for the final page count and pass --per-page.

The back-cover text is Mitch's to write: put it in tools/print_details.json as
"back_cover" (blank lines separate paragraphs). Until then the cover shows a
marked placeholder. The barcode area is left blank; the service adds the
barcode for the ISBN.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
TRIM_W, TRIM_H, BLEED = 6.0, 9.0, 0.125
PER_PAGE = {"white": 0.002252, "cream": 0.0025}  # KDP, black-and-white interior


def page_count(pdf: pathlib.Path) -> int:
    info = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True, check=True).stdout
    return int(re.search(r"^Pages:\s+(\d+)", info, re.M).group(1))


def tstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pages", type=int)
    ap.add_argument("--paper", choices=PER_PAGE, default="white")
    ap.add_argument("--per-page", type=float, help="paper thickness in inches per page (overrides --paper)")
    ap.add_argument("--guides", action="store_true")
    a = ap.parse_args()
    pages = a.pages or page_count(ROOT / "build" / "book-print.pdf")
    spine = pages * (a.per_page or PER_PAGE[a.paper])
    details_path = ROOT / "tools" / "print_details.json"
    details = json.loads(details_path.read_text()) if details_path.exists() else {}
    back = details.get("back_cover", "")
    back_markup = ("[" + "\n\n".join(re.sub(r"([\\#$*_`<>@\[\]~=/])", r"\\\1", p.strip())
                                      for p in back.split("\n\n") if p.strip()) + "]") if back else "none"
    width = 2 * TRIM_W + spine + 2 * BLEED
    height = TRIM_H + 2 * BLEED
    (ROOT / "build" / "cover.typ").write_text(f'''// Generated by tools/build_cover.py: {pages} pages, spine {spine:.3f} in.
#import "cover-design.typ": cover
#cover(trim-w: {TRIM_W}in, trim-h: {TRIM_H}in, bleed: {BLEED}in, spine: {spine:.4f}in,
  back-text: {back_markup}, guides: {str(a.guides).lower()})
''')
    print(f"{pages} pages, spine {spine:.3f} in, cover {width:.3f} × {height:.3f} in → build/cover.typ")
    if not back:
        print("COVER NOT READY: no back_cover text in tools/print_details.json")


if __name__ == "__main__":
    main()
