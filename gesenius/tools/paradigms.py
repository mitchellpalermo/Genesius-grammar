def _h(s: str) -> str:
    """Wrap each Hebrew run of a cell in {{GHGheb}}: `{…}` marks a run."""
    import re
    return re.sub(r"(?<!\{)\{([^{}]+)\}(?!\})",
                  lambda m: "{{GHGheb|text=" + m.group(1) + "}}", s)


